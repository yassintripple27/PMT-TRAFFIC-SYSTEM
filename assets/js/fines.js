/* PTM — Fines & Payments page */
(function () {
  'use strict';
  const U = PTM.util;
  PTM.init({ active: 'fines' });

  const state = { q: '', status: 'all', shown: 25 };
  const METHODS = ['MTN MOBILE MONEY', 'AIRTEL MONEY', 'BANK TRANSFER', 'VISA / MASTERCARD'];
  const REF_HINT = {
    'MTN MOBILE MONEY': 'MoMo phone number (e.g. 0772 000 111)',
    'AIRTEL MONEY': 'Airtel Money phone number (e.g. 0758 000 222)',
    'BANK TRANSFER': 'Bank transfer reference',
    'VISA / MASTERCARD': 'Card last 4 digits (e.g. 4712)'
  };

  function filtered() {
    let list = PTM.cases.all().filter(c => c.status !== 'DISMISSED' && c.status !== 'RESOLVED' || c.status === 'PAID');
    if (state.status !== 'all') list = list.filter(c => c.status === state.status);
    if (state.q) {
      const q = state.q.toLowerCase();
      list = list.filter(c =>
        c.plate.toLowerCase().includes(q) || c.id.toLowerCase().includes(q) ||
        (c.payment && c.payment.receipt.toLowerCase().includes(q)));
    }
    return list;
  }

  function renderKpis() {
    const unpaid = PTM.cases.unpaid();
    const paid = PTM.cases.paid();
    const outstanding = unpaid.reduce((a, c) => a + c.penalty, 0);
    const collected = paid.reduce((a, c) => a + c.penalty, 0);
    const receipts = Object.values(PTM.cases.payments()).filter(p => p.receipt).length;
    document.getElementById('f-kpis').innerHTML = [
      ['Outstanding', U.ugx(outstanding), U.num(unpaid.length) + ' unpaid fines'],
      ['Collected', U.ugx(collected), U.num(paid.length) + ' settled cases'],
      ['Receipts issued', U.num(receipts), 'after approval'],
      ['Awaiting approval', U.num(PTM.cases.awaitingApproval().length), 'payments to review'],
      ['Pending verification', U.num(PTM.cases.pending().length), 'not yet enforceable']
    ].map(k => `<div class="kpi"><div class="kpi-label">${k[0]}</div><div class="kpi-value" style="font-size:1.25rem">${k[1]}</div><div class="kpi-sub">${k[2]}</div></div>`).join('');
  }

  function render() {
    const list = filtered();
    document.getElementById('count').textContent = U.num(list.length) + ' fines';
    document.getElementById('body').innerHTML = list.slice(0, state.shown).map(c => `
      <tr>
        <td class="mono">${U.esc(c.id)}</td>
        <td><span class="plate">${U.esc(c.plate)}</span></td>
        <td>${U.esc(c.violationLabel)}</td>
        <td class="muted mono tiny">${U.esc(c.date)}</td>
        <td class="mono">${U.ugx(c.penalty)}</td>
        <td><span class="badge ${c.status === 'PAID' ? 'badge-paid' : c.status === 'UNPAID' ? 'badge-unpaid' : 'badge-pending'}">${U.esc(c.status)}</span></td>
        <td class="mono tiny">${c.payment && c.payment.receipt ? U.esc(c.payment.receipt) : c.payment && c.payment.status === 'PENDING APPROVAL' ? '<span class="badge badge-pending">AWAITING APPROVAL</span>' : '<span class="muted-2">—</span>'}</td>
        <td>
          ${c.status === 'UNPAID' ? `<button class="btn btn-gold btn-xs" data-pay="${U.esc(c.id)}">Pay</button>` : ''}
          ${c.payment && c.payment.receipt ? `<button class="btn btn-ghost btn-xs" data-receipt="${U.esc(c.id)}">Receipt</button>` : ''}
        </td>
      </tr>`).join('') || '<tr><td colspan="8" class="empty">No fines match the current filters.</td></tr>';
    document.getElementById('more').style.display = state.shown < list.length ? '' : 'none';
  }

  function receiptHTML(rec, c) {
    return `
      <div class="receipt">
        <h4>PTM UGANDA — OFFICIAL RECEIPT</h4>
        <div class="r-sub">POLICE TRAFFIC MANAGEMENT · SIMULATED DOCUMENT</div>
        <div class="r-row"><span>Receipt No.</span><b>${U.esc(rec.receipt)}</b></div>
        <div class="r-row"><span>Reference</span><b>${U.esc(rec.reference)}</b></div>
        <div class="r-row"><span>Case</span><b>${U.esc(rec.caseId)}</b></div>
        <div class="r-row"><span>Vehicle plate</span><b>${U.esc(rec.plate)}</b></div>
        <div class="r-row"><span>Violation</span><b>${U.esc(c ? c.violationLabel : '')}</b></div>
        <div class="r-row"><span>Method</span><b>${U.esc(rec.method)}</b></div>
        <div class="r-row"><span>Approved by</span><b>${U.esc(rec.approvedBy || '—')}</b></div>
        <div class="r-row"><span>Date / time</span><b>${U.esc(rec.date)} ${U.esc(rec.time)}</b></div>
        <div class="r-row r-total"><span>TOTAL PAID</span><b>${U.ugx(rec.amount)}</b></div>
        <div class="r-sub" style="margin:14px 0 0">This is a simulated receipt generated by the PTM prototype. It is not a legal document.</div>
      </div>`;
  }

  function showReceipt(c) {
    PTM.audit('RECEIPT_VIEW', { caseId: c.id, receipt: c.payment.receipt });
    const m = PTM.modal({
      title: 'Receipt ' + c.payment.receipt,
      subtitle: c.id + ' · ' + c.plate,
      width: 460,
      body: receiptHTML(c.payment, c),
      footer: `<button class="btn btn-outline" id="rc-print">Print</button><button class="btn btn-ghost" data-close>Close</button>`
    });
    m.el.querySelector('[data-close]').addEventListener('click', m.close);
    m.el.querySelector('#rc-print').addEventListener('click', () => window.print());
  }

  function payFlow(c) {
    if (!PTM.session.require('payments', 'Processing payments requires Payment Officer or Super Admin authority.')) return;
    const m = PTM.modal({
      title: 'Settle fine — ' + c.id,
      subtitle: c.plate + ' · ' + c.violationLabel + ' · ' + U.ugx(c.penalty),
      width: 520,
      body: `
        <div class="field">
          <label for="pm">Payment method</label>
          <select class="input" id="pm">${METHODS.map(x => `<option>${x}</option>`).join('')}</select>
        </div>
        <div class="field" style="margin-top:14px">
          <label for="pm-ref" id="pm-ref-label">${U.esc(REF_HINT[METHODS[0]])}</label>
          <input class="input" id="pm-ref" placeholder="Optional — auto reference will be generated if left blank">
        </div>
        <div class="notice" style="margin-top:16px">
          <svg viewBox="0 0 24 24" width="16" height="16" fill="currentColor"><path d="M12 2L1 21h22L12 2zm1 14h-2v2h2v-2zm0-7h-2v5h2V9z"/></svg>
          <div>No real money moves in this prototype. Confirming submits the payment for authorisation; an official simulated receipt is issued only after an authorized payment officer approves it.</div>
        </div>`,
      footer: `<button class="btn btn-gold" id="pm-confirm">Submit ${U.ugx(c.penalty)}</button><button class="btn btn-ghost" data-close>Cancel</button>`
    });
    const sel = m.el.querySelector('#pm');
    sel.addEventListener('change', () => { m.el.querySelector('#pm-ref-label').textContent = REF_HINT[sel.value] || 'Reference'; });
    m.el.querySelector('[data-close]').addEventListener('click', m.close);
    m.el.querySelector('#pm-confirm').addEventListener('click', () => {
      const method = sel.value;
      const ref = m.el.querySelector('#pm-ref').value.trim();
      const rec = PTM.cases.pay(c.id, method, ref);
      m.close();
      PTM.toast('amber', 'Payment submitted', U.ugx(rec.amount) + ' via ' + rec.method + ' — awaiting admin approval.');
      renderKpis(); render();
    });
  }

  let deb;
  document.getElementById('q').addEventListener('input', e => { clearTimeout(deb); deb = setTimeout(() => { state.q = e.target.value; state.shown = 25; render(); }, 200); });
  document.getElementById('status').addEventListener('change', e => { state.status = e.target.value; state.shown = 25; render(); });
  document.getElementById('more').addEventListener('click', () => { state.shown += 25; render(); });
  document.getElementById('body').addEventListener('click', e => {
    const pay = e.target.closest('[data-pay]');
    const rc = e.target.closest('[data-receipt]');
    if (pay) { const c = PTM.cases.get(pay.dataset.pay); if (c) payFlow(c); }
    if (rc) { const c = PTM.cases.get(rc.dataset.receipt); if (c && c.payment) showReceipt(c); }
  });

  renderKpis();
  render();
})();
